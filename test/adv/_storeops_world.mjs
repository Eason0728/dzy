/** 把沙盒的 Date 往後撥 days 天（之後 new Date()／Date.now() 都是撥過的時間；給了明確參數的 new Date(x) 不受影響） */
export function shiftDays(app, days) {
  const Real = app.sb.__RealDate || vm.runInContext('Date', app.sb);
  app.sb.__RealDate = Real;
  const off = days * 86400000;
  app.sb.Date = class extends Real {
    constructor(...a) { if (a.length === 0) super(Real.now() + off); else super(...a); }
    static now() { return Real.now() + off; }
  };
}
